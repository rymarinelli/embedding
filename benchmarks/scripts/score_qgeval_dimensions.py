"""Score questions on QGEval's 7 dimensions with an LLM judge (G-EVAL style).

Emulates QGEval (Fu et al., EMNLP 2024). Two protocol details follow the paper:

  * Chain-of-thought before the score (G-EVAL, Liu et al. 2023) — the paper
    found this the best-correlating automatic proxy for human annotation.
  * All questions for the same passage are judged in a single call, as in the
    paper's annotation protocol ("For the same passage, all 15 questions
    generated by different models were presented simultaneously... helps
    annotators validate their judgments").

Beyond the paper: the two systems are presented BLIND and in randomized order
(as "Question A"/"Question B"), so the judge cannot prefer a system by label
and position bias is averaged out. The mapping is stored per record so scores
can be attributed afterwards.

Both Fable's generated question and NorQuAD's own reference question are
scored — the paper likewise scores the human reference as its own row
(their Table 4), which is what makes "did the model beat the humans?"
answerable.

Requires OPENROUTER_API_KEY in the environment (never hardcode/commit it).

Usage:
    export OPENROUTER_API_KEY=sk-or-...
    python3 score_qgeval_dimensions.py [judge_model]
"""
import json
import os
import random
import sys
import time
from pathlib import Path

import requests

sys.path.insert(0, str(Path(__file__).resolve().parent))
from qgeval_dimensions import DIMENSIONS, rubric_block  # noqa: E402

DATA_DIR = Path(__file__).resolve().parent.parent / "data"
RESULTS_DIR = Path(__file__).resolve().parent.parent / "results"
GEN_PATH = RESULTS_DIR / "qgeval_fable_questions.json"
SAMPLE_PATH = DATA_DIR / "qgeval_sample.json"
OUT_PATH = RESULTS_DIR / "qgeval_judge_scores.json"

OPENROUTER_URL = "https://openrouter.ai/api/v1/chat/completions"
DEFAULT_JUDGE = "anthropic/claude-opus-5"

MAX_PASSAGE_CHARS = 6000
MAX_TOKENS = 2500
TIMEOUT = 180
RETRIES = 3
SEED = 42

SYSTEM_PROMPT = (
    "You are a meticulous annotator evaluating the quality of automatically "
    "generated reading-comprehension questions. The passages and questions are "
    "in Norwegian; the evaluation rubric is in English. You reason briefly "
    "before assigning each score, and you respond only with valid JSON."
)

USER_TEMPLATE = """You will evaluate two candidate questions written for the same Norwegian passage and target answer. Score EACH question independently on all seven dimensions using the scale below (1-3, higher is better).

{rubric}

Passage:
{passage}

Answer:
{answer}

Question A:
{question_a}

Question B:
{question_b}

For every dimension, first give one short sentence of reasoning, then the integer score. Judge each question on its own merits — do not score one relative to the other.

Respond with ONLY valid JSON in exactly this format:
{{
  "A": {{
    "fluency": {{"reason": "...", "score": 3}},
    "clarity": {{"reason": "...", "score": 3}},
    "conciseness": {{"reason": "...", "score": 3}},
    "relevance": {{"reason": "...", "score": 3}},
    "consistency": {{"reason": "...", "score": 3}},
    "answerability": {{"reason": "...", "score": 3}},
    "answer_consistency": {{"reason": "...", "score": 3}}
  }},
  "B": {{ ... same seven keys ... }}
}}"""


def parse_json_reply(text):
    t = text.strip()
    if t.startswith("```"):
        t = t.split("```", 2)[1]
        if t.lstrip().lower().startswith("json"):
            t = t.lstrip()[4:]
    start, end = t.find("{"), t.rfind("}")
    if start != -1 and end != -1:
        t = t[start:end + 1]
    return json.loads(t)


def validate(parsed):
    """Every slot must carry an int score in 1..3, or the record is unusable."""
    for slot in ("A", "B"):
        if slot not in parsed:
            raise ValueError(f"missing slot {slot}")
        for dim in DIMENSIONS:
            if dim not in parsed[slot]:
                raise ValueError(f"missing dimension {dim} in {slot}")
            score = parsed[slot][dim].get("score")
            if not isinstance(score, int) or not 1 <= score <= 3:
                raise ValueError(f"bad score for {slot}.{dim}: {score!r}")
    return parsed


def call_judge(api_key, model, passage, answer, question_a, question_b):
    headers = {"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"}
    user = USER_TEMPLATE.format(
        rubric=rubric_block(),
        passage=passage[:MAX_PASSAGE_CHARS],
        answer=answer,
        question_a=question_a,
        question_b=question_b,
    )
    payload = {
        "model": model,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user},
        ],
        "max_tokens": MAX_TOKENS,
        "temperature": 0.0,
    }
    last_err = None
    for attempt in range(RETRIES):
        try:
            resp = requests.post(OPENROUTER_URL, headers=headers, json=payload, timeout=TIMEOUT)
            if resp.status_code == 200:
                content = resp.json()["choices"][0]["message"]["content"]
                if content:
                    return validate(parse_json_reply(content))
                last_err = "empty content"
            else:
                last_err = f"HTTP {resp.status_code}: {resp.text[:200]}"
        except (requests.RequestException, ValueError, json.JSONDecodeError) as e:
            last_err = str(e)
        time.sleep(2 ** attempt)
    raise RuntimeError(f"judge failed after {RETRIES} attempts: {last_err}")


def main():
    judge_model = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_JUDGE

    api_key = os.environ.get("OPENROUTER_API_KEY")
    if not api_key:
        print("ERROR: set OPENROUTER_API_KEY in the environment", file=sys.stderr)
        sys.exit(1)

    passages = {s["qid"]: s["passage"] for s in json.loads(SAMPLE_PATH.read_text(encoding="utf-8"))}
    generated = json.loads(GEN_PATH.read_text(encoding="utf-8"))
    generated = [g for g in generated if g.get("generated_question") and not g.get("error")]
    print(f"Judging {len(generated)} question pairs with {judge_model}")

    outputs = []
    if OUT_PATH.exists():
        outputs = json.loads(OUT_PATH.read_text(encoding="utf-8"))
    done = {o["qid"] for o in outputs if not o.get("error")}

    rng = random.Random(SEED)
    for i, g in enumerate(generated):
        if g["qid"] in done:
            continue

        # Blind + randomized presentation order.
        fable_is_a = rng.random() < 0.5
        q_a = g["generated_question"] if fable_is_a else g["reference_question"]
        q_b = g["reference_question"] if fable_is_a else g["generated_question"]

        record = {
            "qid": g["qid"],
            "doc_id": g["doc_id"],
            "answer": g["answer"],
            "fable_question": g["generated_question"],
            "reference_question": g["reference_question"],
            "fable_slot": "A" if fable_is_a else "B",
            "judge_model": judge_model,
        }
        try:
            parsed = call_judge(api_key, judge_model, passages[g["qid"]],
                                g["answer"], q_a, q_b)
            fable_slot = "A" if fable_is_a else "B"
            ref_slot = "B" if fable_is_a else "A"
            record["fable_scores"] = {d: parsed[fable_slot][d]["score"] for d in DIMENSIONS}
            record["reference_scores"] = {d: parsed[ref_slot][d]["score"] for d in DIMENSIONS}
            record["fable_reasons"] = {d: parsed[fable_slot][d].get("reason", "") for d in DIMENSIONS}
            record["reference_reasons"] = {d: parsed[ref_slot][d].get("reason", "") for d in DIMENSIONS}
        except Exception as e:
            record["error"] = str(e)

        outputs.append(record)
        if record.get("error"):
            print(f"  [{i+1}/{len(generated)}] qid={g['qid']} [ERROR] {record['error'][:120]}")
        else:
            fa = sum(record["fable_scores"].values()) / len(DIMENSIONS)
            re_ = sum(record["reference_scores"].values()) / len(DIMENSIONS)
            print(f"  [{i+1}/{len(generated)}] qid={g['qid']} fable={fa:.2f} ref={re_:.2f}")
        OUT_PATH.write_text(json.dumps(outputs, ensure_ascii=False, indent=2), encoding="utf-8")

    n_ok = sum(1 for o in outputs if not o.get("error"))
    print(f"\nSaved {len(outputs)} records ({n_ok} scored) to {OUT_PATH}")


if __name__ == "__main__":
    main()
