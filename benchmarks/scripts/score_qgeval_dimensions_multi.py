"""Score QGEval's 7 dimensions for MULTIPLE models at once, per passage.

Extends score_qgeval_dimensions.py (which only compared Fable against the
NorQuAD reference) to the full roster in generate_questions_qgeval_multi.py.
Rather than one pairwise call per model (N calls x 200 passages), every
system's question for a given passage is judged in a SINGLE call — this
matches the paper's own protocol more closely than the pairwise script did
("all 15 questions generated by different models were presented
simultaneously... helps annotators validate their judgments") and is far
cheaper: 200 calls total instead of 200 x N.

Systems are presented BLIND, labeled "Question A/B/C/..." in an order
RANDOMIZED independently per passage, so position cannot correlate with any
one system across the run. The letter->system mapping is stored per record
for attribution afterward.

Requires OPENROUTER_API_KEY in the environment (never hardcode/commit it).

Usage:
    export OPENROUTER_API_KEY=sk-or-...
    python3 score_qgeval_dimensions_multi.py [judge_model]
"""
import json
import os
import random
import string
import sys
import time
from pathlib import Path

import requests

sys.path.insert(0, str(Path(__file__).resolve().parent))
from qgeval_dimensions import DIMENSIONS, rubric_block  # noqa: E402
from generate_questions_qgeval_multi import MODELS  # noqa: E402

DATA_DIR = Path(__file__).resolve().parent.parent / "data"
RESULTS_DIR = Path(__file__).resolve().parent.parent / "results"
QGEN_DIR = RESULTS_DIR / "qgeval_questions"
SAMPLE_PATH = DATA_DIR / "qgeval_sample.json"
OUT_PATH = RESULTS_DIR / "qgeval_judge_scores_multi.json"

OPENROUTER_URL = "https://openrouter.ai/api/v1/chat/completions"
DEFAULT_JUDGE = "anthropic/claude-opus-5"

MAX_PASSAGE_CHARS = 6000
MAX_TOKENS = 4000
TIMEOUT = 240
RETRIES = 3
SEED = 42

# "reference" stands for NorQuAD's own human-written question — scored
# alongside the models for the same reason the paper scores its human
# reference as its own row (their Table 4).
REFERENCE_KEY = "norquad-reference"

SYSTEM_PROMPT = (
    "You are a meticulous annotator evaluating the quality of automatically "
    "generated reading-comprehension questions. The passages and questions are "
    "in Norwegian; the evaluation rubric is in English. You reason briefly "
    "before assigning each score, and you respond only with valid JSON."
)

USER_TEMPLATE = """You will evaluate {n} candidate questions written for the same Norwegian passage and target answer. Score EACH question independently on all seven dimensions using the scale below (1-3, higher is better).

{rubric}

Passage:
{passage}

Answer:
{answer}

{questions_block}

For every dimension, first give one short sentence of reasoning, then the integer score. Judge each question ENTIRELY on its own merits — do not compare or rank them against each other.

Respond with ONLY valid JSON in exactly this format (one top-level key per letter shown above):
{{
{schema_block}
}}"""


def build_schema_block(letters):
    dim_lines = ",\n".join(
        f'    "{d}": {{"reason": "...", "score": 3}}' for d in DIMENSIONS
    )
    return ",\n".join(f'  "{L}": {{\n{dim_lines}\n  }}' for L in letters)


def parse_json_reply(text):
    t = text.strip()
    if t.startswith("```"):
        t = t.split("```", 2)[1]
        if t.lstrip().lower().startswith("json"):
            t = t.lstrip()[4:]
    start, end = t.find("{"), t.rfind("}")
    if start != -1 and end != -1:
        t = t[start:end + 1]
    return json.loads(t)


def validate(parsed, letters):
    for L in letters:
        if L not in parsed:
            raise ValueError(f"missing slot {L}")
        for dim in DIMENSIONS:
            if dim not in parsed[L]:
                raise ValueError(f"missing dimension {dim} in {L}")
            score = parsed[L][dim].get("score")
            if not isinstance(score, int) or not 1 <= score <= 3:
                raise ValueError(f"bad score for {L}.{dim}: {score!r}")
    return parsed


def call_judge(api_key, model, passage, answer, letters, questions):
    questions_block = "\n\n".join(
        f"Question {L}:\n{q}" for L, q in zip(letters, questions)
    )
    user = USER_TEMPLATE.format(
        n=len(letters), rubric=rubric_block(), passage=passage[:MAX_PASSAGE_CHARS],
        answer=answer, questions_block=questions_block,
        schema_block=build_schema_block(letters),
    )
    headers = {"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"}
    payload = {
        "model": model,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user},
        ],
        "max_tokens": MAX_TOKENS,
        "temperature": 0.0,
    }
    last_err = None
    for attempt in range(RETRIES):
        try:
            resp = requests.post(OPENROUTER_URL, headers=headers, json=payload, timeout=TIMEOUT)
            if resp.status_code == 200:
                content = resp.json()["choices"][0]["message"]["content"]
                if content:
                    return validate(parse_json_reply(content), letters)
                last_err = "empty content"
            else:
                last_err = f"HTTP {resp.status_code}: {resp.text[:200]}"
        except (requests.RequestException, ValueError, json.JSONDecodeError) as e:
            last_err = str(e)
        time.sleep(2 ** attempt)
    raise RuntimeError(f"judge failed after {RETRIES} attempts: {last_err}")


def load_system_questions():
    """{qid: {system_label: question_text}} across every model that produced
    output, plus the NorQuAD reference. A model missing a qid (failed
    generation) is simply absent from that passage's dict — every passage can
    therefore have a different roster, which the per-passage schema handles."""
    by_qid = {}
    for label in MODELS:
        path = QGEN_DIR / f"{label}.json"
        if not path.exists():
            continue
        for rec in json.loads(path.read_text(encoding="utf-8")):
            if not rec.get("generated_question") or rec.get("error"):
                continue
            by_qid.setdefault(rec["qid"], {})[label] = rec["generated_question"]
            by_qid[rec["qid"]].setdefault(REFERENCE_KEY, rec["reference_question"])
    return by_qid


def main():
    judge_model = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_JUDGE
    api_key = os.environ.get("OPENROUTER_API_KEY")
    if not api_key:
        print("ERROR: set OPENROUTER_API_KEY in the environment", file=sys.stderr)
        sys.exit(1)

    samples = {s["qid"]: s for s in json.loads(SAMPLE_PATH.read_text(encoding="utf-8"))}
    by_qid = load_system_questions()
    if not by_qid:
        print(f"No question files found in {QGEN_DIR}. Run "
              "generate_questions_qgeval_multi.py first.")
        sys.exit(1)

    present_systems = sorted({sys_ for d in by_qid.values() for sys_ in d})
    print(f"Judging {len(by_qid)} passages across systems: {', '.join(present_systems)}")
    print(f"Judge: {judge_model}")

    outputs = []
    if OUT_PATH.exists():
        outputs = json.loads(OUT_PATH.read_text(encoding="utf-8"))
    done = {o["qid"] for o in outputs if not o.get("error")}

    rng = random.Random(SEED)
    qids = sorted(by_qid)
    for i, qid in enumerate(qids):
        if qid in done:
            continue
        s = samples[qid]
        systems = sorted(by_qid[qid])   # deterministic order pre-shuffle
        order = systems[:]
        rng.shuffle(order)
        letters = list(string.ascii_uppercase[:len(order)])
        letter_to_system = dict(zip(letters, order))
        questions = [by_qid[qid][sys_] for sys_ in order]

        record = {
            "qid": qid, "doc_id": s["doc_id"], "answer": s["answer"],
            "systems": systems, "letter_to_system": letter_to_system,
            "judge_model": judge_model,
        }
        try:
            parsed = call_judge(api_key, judge_model, s["passage"], s["answer"], letters, questions)
            record["scores"] = {
                letter_to_system[L]: {d: parsed[L][d]["score"] for d in DIMENSIONS}
                for L in letters
            }
            record["reasons"] = {
                letter_to_system[L]: {d: parsed[L][d].get("reason", "") for d in DIMENSIONS}
                for L in letters
            }
        except Exception as e:
            record["error"] = str(e)

        outputs.append(record)
        if record.get("error"):
            print(f"  [{i+1}/{len(qids)}] qid={qid} [ERROR] {record['error'][:120]}")
        else:
            avgs = {sys_: sum(v.values()) / len(DIMENSIONS)
                    for sys_, v in record["scores"].items()}
            print(f"  [{i+1}/{len(qids)}] qid={qid} " +
                  " ".join(f"{s_}={a:.2f}" for s_, a in avgs.items()))
        OUT_PATH.write_text(json.dumps(outputs, ensure_ascii=False, indent=2), encoding="utf-8")

    n_ok = sum(1 for o in outputs if not o.get("error"))
    print(f"\nSaved {len(outputs)} records ({n_ok} scored) to {OUT_PATH}")


if __name__ == "__main__":
    main()
